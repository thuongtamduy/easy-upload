function out($data, int $code = 200): never {
    if ($code >= 500 && isset($data['error'])) {
        $msg = "🚨 <b>Easy Upload Error</b>\nCode: <code>$code</code>\nError: <code>" . htmlspecialchars((string)$data['error']) . "</code>";
